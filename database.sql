-- 1. DROP EXISTING TABLES (Safe Migration)
DROP TABLE IF EXISTS referrals CASCADE;
DROP TABLE IF EXISTS vendors CASCADE;

-- ==============================================================================
-- 2. VENDORS TABLE (With image_url & instagram_handle)
-- ==============================================================================
CREATE TABLE vendors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name TEXT NOT NULL,
  category TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT 'Godhra',
  price_range TEXT NOT NULL,
  phone TEXT NOT NULL,
  description TEXT,
  rating NUMERIC(2,1) DEFAULT 4.9,
  is_verified BOOLEAN DEFAULT TRUE,
  image_url TEXT,
  instagram_handle TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX idx_vendors_category ON vendors (category);
CREATE INDEX idx_vendors_location ON vendors (location);

ALTER TABLE vendors ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public vendors are viewable by everyone" 
  ON vendors FOR SELECT 
  USING (true);

CREATE POLICY "Public can register a vendor" 
  ON vendors FOR INSERT 
  WITH CHECK (true);

-- ==============================================================================
-- 3. REFERRALS (REFER & EARN - ₹10,000 REWARD MODEL) TABLE
-- ==============================================================================
CREATE TABLE referrals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name TEXT NOT NULL,
  client_phone TEXT NOT NULL,
  event_details TEXT NOT NULL,
  agent_name TEXT NOT NULL,
  agent_phone TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending',
  reward_amount TEXT DEFAULT 'Up to ₹10,000',
  admin_notes TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX idx_referrals_status ON referrals (status);
CREATE INDEX idx_referrals_agent_phone ON referrals (agent_phone);

ALTER TABLE referrals ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can submit a referral lead" 
  ON referrals FOR INSERT 
  WITH CHECK (true);

CREATE POLICY "Allow select on referrals for dashboard" 
  ON referrals FOR SELECT 
  USING (true);

-- ==============================================================================
-- 3B. ENQUIRIES (ONE-CLICK EVENT REQUIREMENT & GET 5 QUOTES) TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_code TEXT UNIQUE NOT NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  event_type TEXT NOT NULL DEFAULT 'wedding',
  location TEXT NOT NULL DEFAULT 'Godhra',
  event_date TEXT NOT NULL,
  guest_count TEXT DEFAULT '350-700',
  services JSONB NOT NULL DEFAULT '[]'::jsonb,
  budget TEXT,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'Dispatched to Vendors',
  matched_vendor_ids JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_enquiries_code ON enquiries (enquiry_code);
CREATE INDEX IF NOT EXISTS idx_enquiries_status ON enquiries (status);
CREATE INDEX IF NOT EXISTS idx_enquiries_date ON enquiries (event_date);

ALTER TABLE enquiries ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can submit an event enquiry"
  ON enquiries FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Public can view enquiries for quote matching"
  ON enquiries FOR SELECT
  USING (true);

-- ==============================================================================
-- 3C. QUOTES (VERIFIED VENDOR PROPOSALS) TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_code TEXT NOT NULL,
  vendor_id BIGINT REFERENCES vendors(id) ON DELETE CASCADE,
  vendor_name TEXT NOT NULL,
  category TEXT NOT NULL,
  quoted_price TEXT NOT NULL,
  package_details TEXT NOT NULL,
  valid_until TEXT DEFAULT '15 Days',
  status TEXT NOT NULL DEFAULT 'Sent',
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_quotes_enquiry ON quotes (enquiry_code);
CREATE INDEX IF NOT EXISTS idx_quotes_vendor ON quotes (vendor_id);

ALTER TABLE quotes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can view and submit quotes"
  ON quotes FOR ALL
  USING (true)
  WITH CHECK (true);

-- ==============================================================================
-- 3D. VENDOR AVAILABILITY & DOUBLE-BOOKING PROTECTION TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS vendor_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT REFERENCES vendors(id) ON DELETE CASCADE,
  event_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'available', -- 'available' | 'booked' | 'blocked' | 'pending_enquiry'
  notes TEXT,
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
  CONSTRAINT unique_vendor_event_date UNIQUE (vendor_id, event_date)
);

CREATE INDEX IF NOT EXISTS idx_avail_vendor_date ON vendor_availability (vendor_id, event_date);
CREATE INDEX IF NOT EXISTS idx_avail_status ON vendor_availability (status);

ALTER TABLE vendor_availability ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public can check vendor availability"
  ON vendor_availability FOR SELECT
  USING (true);

CREATE POLICY "Authorized vendors can update their availability"
  ON vendor_availability FOR ALL
  USING (true)
  WITH CHECK (true);

-- ==============================================================================
-- 3E. AUDIT LOGS (SECURITY & PRIVACY MONITORING) TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  details TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

ALTER TABLE audit_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins can view audit logs"
  ON audit_logs FOR ALL
  USING (true)
  WITH CHECK (true);

