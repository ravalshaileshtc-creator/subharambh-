-- 1. ROLES & ENUM TYPES
DO $$ BEGIN
  CREATE TYPE user_role_type AS ENUM ('customer', 'vendor', 'admin');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE vendor_approval_status AS ENUM ('pending', 'approved', 'rejected');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- ==============================================================================
-- 2. ENHANCE VENDORS TABLE WITH USER LINK & APPROVAL STATUS
-- ==============================================================================
ALTER TABLE IF EXISTS public.vendors 
  ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS approval_status vendor_approval_status DEFAULT 'approved',
  ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS rating_count INT DEFAULT 18;

-- ==============================================================================
-- 3. PROFILES TABLE (PROTECTED USER ROLES)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  full_name TEXT NOT NULL,
  phone TEXT,
  role user_role_type NOT NULL DEFAULT 'customer',
  vendor_id BIGINT REFERENCES public.vendors(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_profiles_role ON public.profiles (role);
CREATE INDEX IF NOT EXISTS idx_profiles_vendor ON public.profiles (vendor_id);

-- ==============================================================================
-- 4. BOOKINGS TABLE (MULTI-TENANT CUSTOMER, VENDOR & ADMIN ACCESS)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code TEXT UNIQUE NOT NULL,
  customer_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  vendor_id BIGINT REFERENCES public.vendors(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  event_date DATE NOT NULL,
  event_location TEXT NOT NULL,
  guest_count TEXT,
  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  internal_vendor_cost NUMERIC(12,2) DEFAULT 0, -- PROTECTED: Admin-only
  company_margin NUMERIC(12,2) DEFAULT 0,       -- PROTECTED: Admin-only
  status TEXT NOT NULL DEFAULT 'Pending',        -- 'Pending' | 'Confirmed' | 'Completed' | 'Cancelled'
  payment_status TEXT NOT NULL DEFAULT 'Pending',-- 'Pending' | 'Partial' | 'Paid'
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_bookings_customer ON public.bookings (customer_id);
CREATE INDEX IF NOT EXISTS idx_bookings_vendor ON public.bookings (vendor_id);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON public.bookings (status);

-- ==============================================================================
-- 5. PAYMENTS & EARNINGS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT REFERENCES public.bookings(id) ON DELETE CASCADE,
  customer_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  vendor_id BIGINT REFERENCES public.vendors(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL,
  payment_type TEXT NOT NULL, -- 'customer_advance', 'vendor_payout', 'full_settlement'
  payment_method TEXT NOT NULL DEFAULT 'UPI', -- 'UPI', 'NetBanking', 'Cash'
  transaction_ref TEXT,
  status TEXT NOT NULL DEFAULT 'Completed',
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_payments_booking ON public.payments (booking_id);
CREATE INDEX IF NOT EXISTS idx_payments_vendor ON public.payments (vendor_id);

-- ==============================================================================
-- 6. COMPANY FINANCIALS & PROFIT REPORTS (ADMIN-ONLY ACCESS)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.company_financials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  financial_year TEXT NOT NULL,
  total_revenue NUMERIC(12,2) NOT NULL DEFAULT 0,
  vendor_payouts NUMERIC(12,2) NOT NULL DEFAULT 0,
  platform_commission NUMERIC(12,2) NOT NULL DEFAULT 0,
  net_company_profit NUMERIC(12,2) NOT NULL DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- ==============================================================================
-- 7. SECURE SERVER-SIDE RBAC FUNCTIONS (SECURITY DEFINER)
-- ==============================================================================

-- Check if current authenticated user is an Admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Check if current authenticated user is a Vendor
CREATE OR REPLACE FUNCTION public.is_vendor()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'vendor'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Get current authenticated user's verified vendor_id
CREATE OR REPLACE FUNCTION public.get_my_vendor_id()
RETURNS BIGINT AS $$
DECLARE
  v_id BIGINT;
BEGIN
  SELECT vendor_id INTO v_id FROM public.profiles WHERE id = auth.uid();
  RETURN v_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Get current authenticated user's role
CREATE OR REPLACE FUNCTION public.get_current_user_role()
RETURNS user_role_type AS $$
DECLARE
  u_role user_role_type;
BEGIN
  SELECT role INTO u_role FROM public.profiles WHERE id = auth.uid();
  RETURN COALESCE(u_role, 'customer'::user_role_type);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ==============================================================================
-- 8. TRIGGERS: AUTOMATIC SIGNUP ROLE & PREVENT ROLE TAMPERING
-- ==============================================================================

-- 8.1 Auto-create profile with DEFAULT 'customer' role on public signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, phone, role)
  VALUES (
    new.id,
    new.email,
    COALESCE(new.raw_user_meta_data->>'full_name', 'Customer User'),
    COALESCE(new.raw_user_meta_data->>'phone', ''),
    'customer'::user_role_type
  )
  ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 8.2 Prevent users from tampering with their own role
CREATE OR REPLACE FUNCTION public.prevent_role_tampering()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.role IS DISTINCT FROM OLD.role THEN
    -- Only an existing admin or Postgres service_role can change user roles
    IF NOT public.is_admin() AND current_user != 'service_role' THEN
      RAISE EXCEPTION 'Access Denied: You are not authorized to modify user roles.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_prevent_role_tampering ON public.profiles;
CREATE TRIGGER trg_prevent_role_tampering
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.prevent_role_tampering();

-- ==============================================================================
-- 9. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

-- 9.1 PROFILES RLS
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can read own profile or Admins read all" ON public.profiles;
CREATE POLICY "Users can read own profile or Admins read all"
  ON public.profiles FOR SELECT
  USING (auth.uid() = id OR public.is_admin());

DROP POLICY IF EXISTS "Users can update own name and phone" ON public.profiles;
CREATE POLICY "Users can update own name and phone"
  ON public.profiles FOR UPDATE
  USING (auth.uid() = id OR public.is_admin())
  WITH CHECK (auth.uid() = id OR public.is_admin());

-- 9.2 VENDORS RLS
ALTER TABLE public.vendors ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view approved vendors" ON public.vendors;
CREATE POLICY "Public can view approved vendors"
  ON public.vendors FOR SELECT
  USING (
    approval_status = 'approved' 
    OR auth.uid() = user_id 
    OR public.is_admin()
  );

DROP POLICY IF EXISTS "Vendors can update own profile" ON public.vendors;
CREATE POLICY "Vendors can update own profile"
  ON public.vendors FOR UPDATE
  USING (auth.uid() = user_id OR public.is_admin())
  WITH CHECK (auth.uid() = user_id OR public.is_admin());

DROP POLICY IF EXISTS "Public can register pending vendor" ON public.vendors;
CREATE POLICY "Public can register pending vendor"
  ON public.vendors FOR INSERT
  WITH CHECK (true);

-- 9.3 BOOKINGS RLS
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Customers and Vendors see assigned bookings, Admins see all" ON public.bookings;
CREATE POLICY "Customers and Vendors see assigned bookings, Admins see all"
  ON public.bookings FOR SELECT
  USING (
    auth.uid() = customer_id
    OR vendor_id = public.get_my_vendor_id()
    OR public.is_admin()
  );

DROP POLICY IF EXISTS "Customers can create booking requests" ON public.bookings;
CREATE POLICY "Customers can create booking requests"
  ON public.bookings FOR INSERT
  WITH CHECK (auth.uid() = customer_id OR public.is_admin());

DROP POLICY IF EXISTS "Assigned vendors and admins can update booking status" ON public.bookings;
CREATE POLICY "Assigned vendors and admins can update booking status"
  ON public.bookings FOR UPDATE
  USING (
    vendor_id = public.get_my_vendor_id()
    OR auth.uid() = customer_id
    OR public.is_admin()
  );

-- 9.4 PAYMENTS RLS
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Parties can view their payments" ON public.payments;
CREATE POLICY "Parties can view their payments"
  ON public.payments FOR SELECT
  USING (
    auth.uid() = customer_id
    OR vendor_id = public.get_my_vendor_id()
    OR public.is_admin()
  );

-- 9.5 COMPANY FINANCIALS & PROFIT REPORTS (ADMIN-ONLY STRICT ISOLATION)
ALTER TABLE public.company_financials ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Strict Admin Only Access on Company Financials" ON public.company_financials;
CREATE POLICY "Strict Admin Only Access on Company Financials"
  ON public.company_financials FOR ALL
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

